/** Подсчёт результата теста по ответам (1–5 для шкал или индексу варианта). */
export function scoreTest(test: TestDef, answers: Record<string, number>) {
  const scores: Record<string, number> = {}
  for (const qq of test.questions) {
    const a = answers[qq.id]
    if (a == null) continue
    if (qq.options) {
      for (const [k, w] of Object.entries(qq.options[a]?.weights ?? {})) scores[k] = (scores[k] ?? 0) + w
    } else if (qq.scale) scores[qq.scale] = (scores[qq.scale] ?? 0) + a
  }
  if (test.kind === 'mbti') {
    const pick = (a: string, b: string) => ((scores[a] ?? 0) >= (scores[b] ?? 0) ? a : b)
    const type = pick('E', 'I') + pick('S', 'N') + pick('T', 'F') + pick('J', 'P')
    return { scores, top: [type], summary: type }
  }
  const sorted = test.scales.map((s) => s.id).sort((a, b) => (scores[b] ?? 0) - (scores[a] ?? 0))
  const top = sorted.slice(0, 2)
  return { scores, top, summary: test.scales.find((s) => s.id === top[0])?.name ?? '' }
}
